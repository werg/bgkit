#!/usr/bin/env python
"""Collect showcase results into the repo: copies every bench / teacher-bench JSON (+ per-item rows)
from the eval dir into results/showcase/ and regenerates results/showcase/RESULTS.md from them --
tables are GENERATED from the result files, never hand-typed.

    .venv/bin/python scripts/bgkit2_showcase_report.py
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

EVAL = Path("/home/werg/bgkit-data-nvme/bgkit2/eval")
OUT = Path(__file__).resolve().parents[1] / "results" / "showcase"
METRICS = ("acc", "em", "f1", "contains", "judge_acc")
COST = ("prefix", "ctx_tokens", "enc_s", "dec_s", "summ_in_tokens", "summ_out_tokens", "summ_s")


def _copy() -> None:
    for sub in ("showcase", "teacher_bench"):
        src = EVAL / sub
        if not src.exists():
            continue
        for f in src.rglob("*"):
            if f.is_file() and f.suffix in (".json", ".jsonl"):
                dst = OUT / sub / f.relative_to(src)
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(f, dst)


def _arm_key(k: str) -> tuple:
    arm, _, b = k.partition("@")
    order = ["bgkit", "text", "base", "summary", "base_summary", "text_full", "base_full"]
    return (int(b) if b.isdigit() else 10**9, order.index(arm) if arm in order else 99, arm)


def _bench_tables() -> list[str]:
    lines = []
    root = OUT / "showcase"
    by_bench: dict[str, list[tuple[str, dict]]] = {}
    for run in sorted(p for p in root.iterdir() if p.is_dir()):
        for f in sorted(run.glob("*.json")):
            by_bench.setdefault(f.stem, []).append((run.name, json.loads(f.read_text())))
    for bench, runs in sorted(by_bench.items()):
        lines.append(f"\n### {bench}\n")
        lines.append("| run | ckpt | n | arm@budget | " + " | ".join(METRICS) + " | decoder prefix | "
                     "context tokens | enc s | dec s | summariser in/out tok, s |")
        lines.append("|" + "---|" * (9 + len(METRICS)))
        for run, d in runs:
            ck = Path(d.get("checkpoint", "")).name.split("_run-")[0].replace("bgkit2_", "")
            # items actually scored per arm (text_full skips contexts over --full-max-tokens)
            rf = root / run / f"{bench}.rows.jsonl"
            n_arm: dict[str, int] = {}
            if rf.exists():
                for ln in rf.read_text().splitlines():
                    if ln.strip():
                        a = json.loads(ln)["arm"]
                        n_arm[a] = n_arm.get(a, 0) + 1
            for k, v in sorted(d.get("summary", {}).items(), key=lambda kv: _arm_key(kv[0])):
                ms = " | ".join(f"{v[m]:.3f}" if m in v else "" for m in METRICS)
                summ = (f"{v['summ_in_tokens']:.0f}/{v['summ_out_tokens']:.0f}, {v['summ_s']:.1f}"
                        if "summ_in_tokens" in v else "")
                lines.append(
                    f"| {run} | {ck} | {n_arm.get(k, d.get('n', ''))} | {k} | {ms} | {v.get('prefix', 0):.0f} | "
                    f"{v.get('ctx_tokens', 0):.0f} | {v['enc_s']:.3f} | {v['dec_s']:.3f} | {summ} |"
                    if "enc_s" in v else
                    f"| {run} | {ck} | {n_arm.get(k, d.get('n', ''))} | {k} | {ms} | {v.get('prefix', 0):.0f} | "
                    f"{v.get('ctx_tokens', 0):.0f} | – | – | {summ} |")
    return lines


def _teacher_table() -> list[str]:
    lines = ["\n## Teacher / sub-agent candidates (digest job, 96 real tool results)\n",
             "Load: runs before 17:40Z 2026-09-21 shared the GPU with the benchmark sweep; `idle` "
             "runs had it to themselves; vllm_* shared it with the production llama.cpp teacher. "
             "`grounded` before 2026-09-21 18:00Z does not yet strip future-narration sentences.\n",
             "| candidate | prompt | concurrency | digests/min | out tok/s | parse | grounded | "
             "next_recall | keep_recall | words | errors |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for f in sorted((OUT / "teacher_bench").glob("*.json")):
        s = json.loads(f.read_text())["summary"]
        lines.append(f"| {s['name']} | {s.get('prompt', 'plain')} | {s['concurrency']} | "
                     f"{s['digests_per_min']} | {s['out_tok_per_s']} | {s['parse']} | "
                     f"{s['grounded']} | {s['next_recall']} | {s.get('keep_recall', '')} | "
                     f"{s['words']} | {s['errors']} |")
    return lines


def main() -> None:
    _copy()
    md = ["# Showcase results (generated by scripts/bgkit2_showcase_report.py — do not edit)\n",
          "Arms: bgkit = context in compressed slots (question = encoder prompt); text = same weights, "
          "plain text middle-truncated to the budget; base = adapter off, same text; text_full / "
          "base_full = the whole context as plain text; summary / base_summary = a larger model's "
          "question-focused summary written to the budget. Metrics: acc (BABILong, RULER, QuALITY), "
          "em / f1 / contains (free-form). Per-item predictions: the matching *.rows.jsonl.",
          "Timing columns are empty for runs made before timing was added to the runner.",
          "\n## Benchmarks"]
    md += _bench_tables()
    md += _teacher_table()
    (OUT / "RESULTS.md").write_text("\n".join(md) + "\n")
    print(f"wrote {OUT / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
